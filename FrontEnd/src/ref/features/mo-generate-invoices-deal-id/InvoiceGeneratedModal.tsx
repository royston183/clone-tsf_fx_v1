import { useEffect, useMemo, useState } from 'react'
import { CheckCircle2, Download, Eye } from 'lucide-react'
import { DataTable } from '@/components/table/DataTable'
import { Modal } from "@/components/ui/Modal"
import { loadLogo } from './branding.ts'
import { loadCompanies } from './companies.ts'
import { statusText } from './format.ts'
import { downloadPdfs, grouped, longDate, pdfFiles, pdfLegs, type PdfFile } from './invoice-pdf.ts'
import type { Deal } from './types.ts'

/**
 * Shown once the invoice numbers are generated: what was generated (deal, status, and each leg's invoice number, date,
 * amount and currency), then Download PDF, and a preview of the generated PDFs inside the screen. The PDFs are made once
 * from the confirmed rows (never by confirming again) and the same bytes serve the preview and the download.
 */
export function InvoiceGeneratedModal({ deal, onClose }: { deal: Deal; onClose: () => void }) {
  const legs = useMemo(() => pdfLegs(deal), [deal])
  const [made, setMade] = useState<{ files: PdfFile[]; error: string } | null>(null)
  const [view, setView] = useState<'summary' | 'preview'>('summary')
  const [current, setCurrent] = useState(0)
  const [busy, setBusy] = useState(false)
  const [note, setNote] = useState('')

  useEffect(() => {
    let live = true
    Promise.all([loadLogo(), loadCompanies()]).then(
      ([logo, companies]) => { if (live) setMade({ files: pdfFiles(deal, logo, companies), error: '' }) },
      (e: unknown) => { if (live) setMade({ files: [], error: e instanceof Error ? e.message : String(e) }) },
    )
    return () => { live = false }
  }, [deal])

  const files = made?.files ?? []
  const shown = files[current]
  // The preview shows the generated bytes themselves (a data URL, so no object URL has to be created and released).
  const url = useMemo(() => {
    if (view !== 'preview' || !shown) return ''
    let bin = ''
    for (let i = 0; i < shown.bytes.length; i += 0x8000) bin += String.fromCharCode(...shown.bytes.subarray(i, i + 0x8000))
    return `data:application/pdf;base64,${btoa(bin)}#toolbar=1&view=FitH`
  }, [view, shown])

  const download = async (list: PdfFile[]) => {
    setBusy(true)
    setNote('')
    try {
      await downloadPdfs(list)
      setNote(list.length === 1 ? `${list[0]?.name} downloaded.` : `${list.length} PDF files downloaded.`)
    } catch (e) {
      setNote(`The download failed: ${e instanceof Error ? e.message : String(e)}`)
    } finally {
      setBusy(false)
    }
  }

  const loading = made === null
  const failed = !!made?.error
  const status = statusText(deal.status)

  if (view === 'preview') {
    return (
      <Modal
        title="Preview your invoice"
        eyebrow={`Deal ID ${deal.dealId}`}
        size="wide"
        onClose={onClose}
        footerStart={<button className="button" type="button" onClick={() => setView('summary')}>Back</button>}
        footer={
          <>
            <button className="button" type="button" disabled={busy || !shown} onClick={() => shown && void download([shown])}><Download size={14} aria-hidden="true" /> Download this PDF</button>
            <button className="button primary" type="button" disabled={busy || !files.length} onClick={() => void download(files)}><Download size={14} aria-hidden="true" /> Download all ({files.length})</button>
            <button className="button" type="button" onClick={onClose}>Close</button>
          </>
        }
      >
        <div className="invgen__tabs" role="tablist" aria-label="Generated PDFs">
          {files.map((f, i) => (
            <button key={f.name} type="button" role="tab" aria-selected={i === current} className={`invgen__tab${i === current ? ' on' : ''}`} onClick={() => setCurrent(i)}>{f.name}</button>
          ))}
        </div>
        {url ? <iframe className="invgen__frame" title={shown?.name ?? 'Invoice PDF'} src={url} /> : <p className="invgen__muted" role="status">Preparing the preview…</p>}
        {note && <p className="invgen__note" role="status">{note}</p>}
      </Modal>
    )
  }

  return (
    <Modal
      title="Invoice Generated Successfully"
      eyebrow="Generate invoice"
      subtitle="The invoice numbers were issued and the Deal ID status is updated."
      size="wide"
      onClose={onClose}
      footer={
        <>
          <button className="button" type="button" disabled={loading || failed} onClick={() => setView('preview')}><Eye size={14} aria-hidden="true" /> View Invoice PDF</button>
          <button className="button primary" type="button" disabled={loading || failed || busy} onClick={() => void download(files)}><Download size={14} aria-hidden="true" /> {busy ? 'Downloading…' : 'Download PDF'}</button>
          <button className="button" type="button" onClick={onClose}>Close</button>
        </>
      }
    >
      <div className="invgen">
        <div className="invgen__ok"><CheckCircle2 size={34} aria-hidden="true" /><div><strong>Invoice generation is completed</strong><span>Deal ID {deal.dealId} · {status}</span></div></div>
        <dl className="invgen__facts">
          <div><dt>Deal ID</dt><dd className="mono">{deal.dealId}</dd></div>
          <div><dt>Invoice status</dt><dd>{status}</dd></div>
        </dl>
        <DataTable nativeLayout nativeExport aria-label="Generated invoices">
          <thead><tr><th>Leg</th><th>Invoice Number</th><th>Invoice Date</th><th className="num">Invoice Amount</th><th>Currency</th></tr></thead>
          <tbody>
            {legs.map((l) => (
              <tr key={`${l.legId}-${l.invNo}`}>
                <td>{l.legId}</td><td className="mono"><b>{l.invNo}</b></td><td>{longDate(l.invDate) || '—'}</td><td className="num">{grouped(l.amount, 2)}</td><td>{l.currency}</td>
              </tr>
            ))}
          </tbody>
        </DataTable>
        <div className="invgen__preview">
          <strong>Preview your invoice</strong>
          <p>Your invoice is ready. Click below to preview the generated PDF before downloading.</p>
          <button className="button" type="button" disabled={loading || failed} onClick={() => setView('preview')}>{loading ? 'Preparing the PDFs…' : 'Preview PDF'}</button>
          {failed && <p className="invgen__error" role="alert">The PDFs could not be prepared: {made?.error}</p>}
        </div>
        {note && <p className="invgen__note" role="status">{note}</p>}
      </div>
    </Modal>
  )
}
