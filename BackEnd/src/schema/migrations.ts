// The generated migration of the module tables, and the plan to bring DB/schema to the module definitions (spec 2026-10-27-app-data-tables §1).
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { inTransaction, migrate, migrations, type Db } from '../db';
import { dbPath } from '../platform-node';
import { diffSchema, readSchema } from './diff';
import { tableName, type TableSpec } from './wanted';

export const GENERATED_MARK = '-- generated by gen-schema';

/** `rename`: the pending migration's SQL is still right, only its name is stale (a teammate's migration took its number). */
export interface MigrationPlan { write?: { file: string; sql: string }; rename?: { from: string; to: string }; remove: string[]; warnings: string[]; refusals: string[]; upToDate: boolean }

const isGenerated = (sql: string): boolean => sql.split('\n')[0].trim() === GENERATED_MARK;
const fileOf = (version: string): string => `${version}.sql`;
const lf = (s: string): string => s.replace(/\r\n/g, '\n');

/**
 * The generated migration's file: its number and the start of its SQL's hash. Two teammates who generate the same number
 * get two names, so Git merges both files instead of reporting a conflict; the same SQL gets the same name and merges cleanly.
 */
export const generatedFile = (n: number, sql: string): string =>
  `${String(n).padStart(4, '0')}_app_tables_${createHash('sha1').update(lf(sql)).digest('hex').slice(0, 8)}.sql`;
const q = (s: string) => `"${s.replace(/"/g, '""')}"`;

/** What the migrations in `schemaDir` should become so the module tables match `wanted`: the frozen ones stay, the pending generated ones are replaced. */
export function planMigrations(schemaDir: string, isFrozen: (file: string) => boolean, wanted: TableSpec[]): MigrationPlan {
  const all = migrations(schemaDir);
  const pending = all.filter(m => isGenerated(m.sql) && !isFrozen(fileOf(m.version)));
  const frozen = all.filter(m => !pending.includes(m));
  const db = new DatabaseSync(':memory:');
  try {
    for (const m of frozen) db.exec(m.sql);
    // Only the module tables are compared: the template's own tables are no business of the diff.
    const current = new Map([...readSchema(db)].filter(([name]) => name.includes('__')));
    const { statements, warnings, refusals } = diffSchema(current, wanted);
    const next = frozen.reduce((n, m) => Math.max(n, Number(m.version.slice(0, 4))), 0) + 1;
    const sql = GENERATED_MARK + '\n' + statements.join('');
    const file = generatedFile(next, sql);
    const same = statements.length > 0 && pending.length === 1 && lf(pending[0].sql) === sql;
    if (statements.length === 0 ? pending.length === 0 : same && fileOf(pending[0].version) === file) return { remove: [], warnings, refusals, upToDate: true };
    // The same SQL under a stale name: renamed, so its tables (and their local data) stay as they are.
    if (same) return { rename: { from: fileOf(pending[0].version), to: file }, remove: [], warnings, refusals, upToDate: false };
    return { write: statements.length === 0 ? undefined : { file, sql }, remove: pending.map(m => fileOf(m.version)), warnings, refusals, upToDate: false };
  } finally {
    db.close();
  }
}

const gitOut = (root: string) => (args: string[]): string => execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });

const blobId = (bytes: Buffer): string => createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex');

/**
 * A migration is frozen once a remote-tracking branch holds this very file (same content, so someone may already run it).
 * A teammate's different file of the same name does not freeze it. Throws when git fails: it never guesses "not frozen".
 */
export function frozenMigrations(root: string, git: (args: string[]) => string = gitOut(root)): (file: string) => boolean {
  if (!existsSync(path.join(root, '.git'))) return () => false;
  const pushed = new Set<string>();
  try {
    const refs = git(['for-each-ref', '--format=%(refname)', 'refs/remotes']).split(/\r?\n/).map(r => r.trim()).filter(Boolean);
    for (const ref of refs) {
      for (const line of git(['ls-tree', ref, 'DB/schema/']).split(/\r?\n/)) {
        const m = /^\d+ blob ([0-9a-f]+)\t(.+)$/.exec(line.trim());
        if (m) pushed.add(`${path.posix.basename(m[2])}\0${m[1]}`);
      }
    }
  } catch (error) {
    throw new Error(`Cannot tell which migrations were pushed: ${error instanceof Error ? error.message : String(error)}.`);
  }
  return file => {
    const full = path.join(root, 'DB', 'schema', file);
    if (!existsSync(full)) return false;
    const bytes = readFileSync(full);
    // A CRLF checkout still equals the LF blob that was pushed.
    const lf = Buffer.from(bytes.toString('utf8').replace(/\r\n/g, '\n'), 'utf8');
    return pushed.has(`${file}\0${blobId(bytes)}`) || pushed.has(`${file}\0${blobId(lf)}`);
  };
}

/** Removes the pending files, then renames or writes the new one. */
export function applyPlan(schemaDir: string, plan: MigrationPlan): void {
  for (const f of plan.remove) rmSync(path.join(schemaDir, f), { force: true });
  if (plan.rename) renameSync(path.join(schemaDir, plan.rename.from), path.join(schemaDir, plan.rename.to));
  if (plan.write) writeFileSync(path.join(schemaDir, plan.write.file), plan.write.sql);
}

const tableExists = (db: Db, name: string): boolean => db.prepare("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?").get(name) !== undefined;

/** Undoes each removed migration the database has applied (indexes, columns, tables, its row, the seeded mark of a module left with no table), one transaction per file; returns the dropped tables. */
export function undoPending(db: Db, removed: { version: string; sql: string }[]): string[] {
  db.exec('CREATE TABLE IF NOT EXISTS schema_migrations (version TEXT NOT NULL PRIMARY KEY, applied_at TEXT NOT NULL)');
  const dropped: string[] = [];
  for (const m of removed) {
    if (!db.prepare('SELECT 1 FROM schema_migrations WHERE version = ?').get(m.version)) continue;
    const tables = [...m.sql.matchAll(/CREATE TABLE (?:IF NOT EXISTS )?"([^"]+)"/g)].map(x => x[1]);
    const columns = [...m.sql.matchAll(/ALTER TABLE "([^"]+)" ADD COLUMN "([^"]+)"/g)].map(x => ({ table: x[1], column: x[2] }));
    const indexes = [...m.sql.matchAll(/CREATE INDEX (?:IF NOT EXISTS )?"([^"]+)"/g)].map(x => x[1]);
    inTransaction(db, () => {
      // Indexes first: SQLite refuses to drop an indexed column.
      for (const ix of indexes) db.exec(`DROP INDEX IF EXISTS ${q(ix)}`);
      for (const { table, column } of columns) {
        if (tables.includes(table) || !tableExists(db, table)) continue;
        const has = (db.prepare(`PRAGMA table_info(${q(table)})`).all() as { name: string }[]).some(c => c.name === column);
        if (has) db.exec(`ALTER TABLE ${q(table)} DROP COLUMN ${q(column)}`);
      }
      for (const t of tables) {
        if (tableExists(db, t)) dropped.push(t);
        db.exec(`DROP TABLE IF EXISTS ${q(t)}`);
      }
      db.prepare('DELETE FROM schema_migrations WHERE version = ?').run(m.version);
      if (tableExists(db, 'app_modules')) {
        const left = (db.prepare("SELECT name FROM sqlite_master WHERE type = 'table'").all() as { name: string }[]).map(r => r.name);
        const touched = new Set(tables.map(t => t.slice(0, t.indexOf('__') + 2)));
        for (const { module_id } of db.prepare('SELECT module_id FROM app_modules').all() as { module_id: string }[]) {
          const prefix = tableName(module_id, '');
          if (touched.has(prefix) && !left.some(n => n.startsWith(prefix))) db.prepare('DELETE FROM app_modules WHERE module_id = ?').run(module_id);
        }
      }
    });
  }
  return dropped;
}

/** `undoPending`, then applies the schema again. */
export function rebuildLocal(db: Db, removed: { version: string; sql: string }[], schemaDir: string): string[] {
  const dropped = undoPending(db, removed);
  migrate(db, schemaDir);
  return dropped;
}

/**
 * gen-schema without --check. The order matters: the local tables are undone first (the files still hold the old pending
 * migrations), then the files change, then the database migrates; a failure before the files change leaves the disk as it was.
 */
export function generate(root: string, wanted: TableSpec[], git?: (args: string[]) => string): { lines: string[]; ok: boolean } {
  const schemaDir = path.join(root, 'DB', 'schema');
  const plan = planMigrations(schemaDir, frozenMigrations(root, git), wanted);
  const lines = [...plan.warnings.map(w => `Schema warning: ${w}`), ...plan.refusals.map(r => `Schema: ${r}`)];
  const removed = plan.remove.map(f => ({ version: f.replace(/\.sql$/, ''), sql: readFileSync(path.join(schemaDir, f), 'utf8') }));
  const file = dbPath(root);
  const db = file !== ':memory:' && existsSync(file) ? new DatabaseSync(file) : undefined;
  try {
    let dropped: string[] = [];
    if (db) {
      db.exec('PRAGMA busy_timeout = 5000');
      db.exec('PRAGMA foreign_keys = ON');
      dropped = undoPending(db, removed);
    }
    applyPlan(schemaDir, plan);
    // The database ran this SQL under the old name: it keeps it, under the new one.
    if (db && plan.rename) db.prepare('UPDATE schema_migrations SET version = ? WHERE version = ?').run(plan.rename.to.replace(/\.sql$/, ''), plan.rename.from.replace(/\.sql$/, ''));
    if (db) migrate(db, schemaDir);
    if (dropped.length) lines.push(`Rebuilt local tables: ${dropped.join(', ')}`);
  } finally {
    db?.close();
  }
  lines.push(plan.write ? `Wrote DB/schema/${plan.write.file}`
    : plan.rename ? `Wrote DB/schema/${plan.rename.to} (renamed from ${plan.rename.from})` : 'Schema: up to date.');
  return { lines, ok: true };
}
